/**
 * @module analytics/events/characters
 * Character-pack export telemetry (Personajes / design.gruia.app).
 *
 * `character_export_result` is emitted BY THE DAEMON after the web client
 * reports a finished export download. The browser only picks `format`;
 * `account_id` is resolved server-side from the daemon's authenticated AMR
 * (Vela) session and `occurred_at` is stamped by the server in UTC — neither
 * is accepted from the request body, so the KPI «accounts exporting ≥1
 * animated character per week» counts real accounts, not devices.
 */

/** Closed set of export formats the KPI understands. Sprite-sheet / frame
 *  PNG downloads are intentionally absent: the metric tracks animated and
 *  full-pack exports only. */
export const CHARACTER_EXPORT_FORMATS = ['gif', 'apng', 'webp', 'pack'] as const;

export type CharacterExportFormat = (typeof CHARACTER_EXPORT_FORMATS)[number];

export function isCharacterExportFormat(value: unknown): value is CharacterExportFormat {
  return (
    typeof value === 'string'
    && (CHARACTER_EXPORT_FORMATS as readonly string[]).includes(value)
  );
}

export interface CharacterExportResultProps {
  format: CharacterExportFormat;
  /** AMR account id resolved server-side; '' when no file-backed sign-in
   *  exists (env-key auth carries no profile). Never a device id. */
  account_id: string;
  /** ISO-8601 UTC timestamp generated by the daemon at capture time. */
  occurred_at: string;
}
